import type { Extraction } from '../domain/types';

function listLine(label: string, items: string[]): string | null {
  return items.length > 0 ? `${label}: ${items.join(', ')}` : null;
}

/**
 * Lines describing the patient, omitting anything that is empty or unknown.
 * @param patient - patient details from the extraction, if any
 */
function patientLines(patient: Extraction['patient']): (string | null)[] {
  const age = patient?.age ?? null;
  return [
    age !== null ? `Age: ${age}` : null,
    listLine('Allergies', patient?.allergies ?? []),
    listLine('Medications', patient?.medications ?? []),
    listLine('Conditions', patient?.conditions ?? []),
  ];
}

/**
 * Builds a plain-text handoff for emergency staff. Contains only what the user supplied
 * and the app extracted; it makes no diagnosis.
 * @param extraction - the (escalated) extraction
 * @returns multi-line text ready to copy or share
 */
export function buildErSummary(extraction: Extraction): string {
  const lines = [
    'EMERGENCY HANDOFF (generated by Sankat Setu, not a diagnosis)',
    `Severity: ${extraction.severity.toUpperCase()}`,
    `Situation: ${extraction.situation_summary}`,
    ...patientLines(extraction.patient),
    listLine('Key facts', extraction.key_facts),
    extraction.location_hint ? `Location: ${extraction.location_hint}` : null,
    listLine('Still unknown', extraction.missing_info),
  ];
  return lines.filter((line): line is string => line !== null).join('\n');
}
